# Pergamino — el módulo "Maccy + Paste" de Escudero:
#   📋 historial de portapapeles, guardado en datos/pergamino.json (0600) o
#      solo en memoria si `persistente: false`
#   🔎 búsqueda sin tildes ni mayúsculas (la usa el buscador ⌃⌥V)
# El reconocimiento de texto en imágenes vive en lector.py.
# Cero nube: ni el historial ni el texto salen del Mac.

import json
import logging
import os
import threading
import time
import unicodedata
from pathlib import Path

log = logging.getLogger("escudero.pergamino")

try:
    from AppKit import NSPasteboard, NSPasteboardTypeString, NSWorkspace
except Exception:
    NSPasteboard = NSWorkspace = None
    NSPasteboardTypeString = "public.utf8-plain-text"

# Marcas estándar de gestores de contraseñas y copias transitorias
# (nspasteboard.org): si están presentes, NI SE MIRA el contenido.
_PRIVADOS = ("org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
             "org.nspasteboard.AutoGeneratedType")

MAX_CARACTERES = 100_000
_MESES = ("ene", "feb", "mar", "abr", "may", "jun",
          "jul", "ago", "sep", "oct", "nov", "dic")


def normalizar(texto):
    """Minúsculas y sin tildes: «Canción» y «cancion» se encuentran igual."""
    descompuesto = unicodedata.normalize("NFKD", str(texto or ""))
    return "".join(c for c in descompuesto if not unicodedata.combining(c)).casefold()


def hace(ts, ahora=None):
    """Cuándo se copió, como lo diría una persona: «hace 5 min», «ayer»…"""
    if not ts:
        return ""
    ahora = time.time() if ahora is None else ahora
    seg = max(0, ahora - ts)
    if seg < 60:
        return "ahora"
    if seg < 3600:
        return f"hace {int(seg // 60)} min"
    copiado, hoy = time.localtime(ts), time.localtime(ahora)
    dias = (time.mktime(hoy[:3] + (0, 0, 0, 0, 0, -1))
            - time.mktime(copiado[:3] + (0, 0, 0, 0, 0, -1))) / 86400
    dias = round(dias)
    if dias <= 0:
        return f"hace {int(seg // 3600)} h"
    if dias == 1:
        return "ayer"
    if dias < 7:
        return f"hace {dias} días"
    return f"{copiado.tm_mday} {_MESES[copiado.tm_mon - 1]}"


# Códigos de tecla físicos de macOS (teclado ANSI/español: misma posición).
_TECLAS = {"a": 0, "s": 1, "d": 2, "f": 3, "h": 4, "g": 5, "z": 6, "x": 7, "c": 8,
           "v": 9, "b": 11, "q": 12, "w": 13, "e": 14, "r": 15, "y": 16, "t": 17,
           "1": 18, "2": 19, "3": 20, "4": 21, "6": 22, "5": 23, "9": 25, "7": 26,
           "8": 28, "0": 29, "o": 31, "u": 32, "i": 34, "p": 35, "l": 37, "j": 38,
           "k": 40, "n": 45, "m": 46, "espacio": 49, "space": 49,
           "izquierda": 123, "left": 123, "←": 123, "derecha": 124, "right": 124, "→": 124,
           "abajo": 125, "down": 125, "↓": 125, "arriba": 126, "up": 126, "↑": 126,
           "enter": 36, "return": 36, "intro": 36, "⏎": 36}
# Cómo se enseña cada tecla especial en el menú.
_NOMBRE_TECLA = {49: "Espacio", 123: "←", 124: "→", 125: "↓", 126: "↑", 36: "⏎"}
# Máscaras de modificador de Carbon y su símbolo.
_MODIFICADORES = {"ctrl": (0x1000, "⌃"), "control": (0x1000, "⌃"), "⌃": (0x1000, "⌃"),
                  "opt": (0x0800, "⌥"), "option": (0x0800, "⌥"), "alt": (0x0800, "⌥"),
                  "⌥": (0x0800, "⌥"),
                  "shift": (0x0200, "⇧"), "mayus": (0x0200, "⇧"), "⇧": (0x0200, "⇧"),
                  "cmd": (0x0100, "⌘"), "command": (0x0100, "⌘"), "⌘": (0x0100, "⌘")}


def parsear_atajo(texto):
    """«ctrl+opt+v» → (código de tecla, máscara Carbon, «⌃⌥V»).
    Lanza ValueError con un mensaje legible si el atajo no vale."""
    partes = [t for t in str(texto or "").lower().replace(" ", "").split("+") if t]
    mascara, simbolos, teclas = 0, set(), []
    for t in partes:
        if t in _MODIFICADORES:
            m, simbolo = _MODIFICADORES[t]
            mascara |= m
            simbolos.add(simbolo)
        elif t in _TECLAS:
            teclas.append(t)
        else:
            raise ValueError(f"no conozco la tecla «{t}» (usa letras, números, espacio, flechas o enter)")
    if len(teclas) != 1:
        raise ValueError("el atajo necesita exactamente una tecla, p. ej. ctrl+opt+v")
    if not mascara or mascara == 0x0200:
        raise ValueError("el atajo necesita ctrl, opt o cmd para no chocar con escribir")
    tecla = teclas[0]
    etiqueta = "".join(s for s in "⌃⌥⇧⌘" if s in simbolos)
    etiqueta += _NOMBRE_TECLA.get(_TECLAS[tecla], tecla.upper())
    return _TECLAS[tecla], mascara, etiqueta


class Pergamino:
    def __init__(self, cfg, ruta=None):
        p = cfg.get("pergamino", {}) or {}
        self.max = int(p.get("maximo", 25))
        self.persistente = bool(p.get("persistente", True)) and ruta is not None
        self.ruta = Path(ruta) if ruta is not None else None
        # Cada entrada: {"texto", "ts", "app"}. La más reciente primero.
        self._entradas = []
        self._lock = threading.RLock()
        self._ultimo_cambio = -1
        self._pb = NSPasteboard.generalPasteboard() if NSPasteboard else None
        # Cuando restauramos un recorte al portapapeles nosotros mismos,
        # anotamos su changeCount para que vigilar() NO lo recapture (sería
        # ruido: el recorte salta al principio del historial sin haberlo
        # copiado el usuario).
        self._cambio_restaurado = None
        if self.persistente:
            self._cargar()
        elif self.ruta is not None and self.ruta.exists():
            # Quien apaga la persistencia no quiere su historial en disco.
            try:
                self.ruta.unlink()
                log.info("persistencia apagada: borrado %s", self.ruta.name)
            except OSError:
                log.warning("no pude borrar %s", self.ruta, exc_info=True)

    def actualizar_config(self, cfg):
        """«Recargar configuración» sin reiniciar: tamaño y persistencia."""
        p = cfg.get("pergamino", {}) or {}
        with self._lock:
            self.max = int(p.get("maximo", 25))
            del self._entradas[self.max:]
            quiere = bool(p.get("persistente", True)) and self.ruta is not None
            if quiere:
                self.persistente = True
                self._guardar()
            elif self.persistente:
                self.persistente = False
                try:
                    self.ruta.unlink()
                except OSError:
                    pass

    @property
    def historial(self):
        """Solo los textos, más reciente primero (lo que pinta el menú)."""
        with self._lock:
            return [e["texto"] for e in self._entradas]

    @property
    def entradas(self):
        with self._lock:
            return [dict(e) for e in self._entradas]

    # ── disco ───────────────────────────────────────────────────────────
    def _cargar(self):
        if not self.ruta.exists():
            return
        try:
            datos = json.loads(self.ruta.read_text(encoding="utf-8"))
            crudas = datos.get("entradas", []) if isinstance(datos, dict) else []
            entradas, vistos = [], set()
            for e in crudas:
                texto = str((e or {}).get("texto") or "")
                if not texto.strip() or texto in vistos or len(texto) > MAX_CARACTERES:
                    continue
                vistos.add(texto)
                entradas.append({"texto": texto,
                                 "ts": float(e.get("ts") or 0),
                                 "app": str(e.get("app") or "")})
            self._entradas = entradas[:self.max]
            log.info("pergamino: %d recortes cargados de disco", len(self._entradas))
        except (OSError, ValueError, TypeError, AttributeError) as e:
            # Un archivo roto no debe tumbar Escudero ni perderse: se aparta.
            apartado = self.ruta.with_suffix(".corrupto.json")
            log.warning("pergamino.json ilegible (%s); lo aparto en %s", e, apartado.name)
            try:
                os.replace(self.ruta, apartado)
            except OSError:
                pass
            self._entradas = []

    def _guardar(self):
        if not self.persistente:
            return
        try:
            self.ruta.parent.mkdir(parents=True, exist_ok=True)
            tmp = self.ruta.with_suffix(".tmp")
            # 0600 desde el primer byte: el historial es solo tuyo.
            fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump({"version": 1, "entradas": self._entradas}, f,
                          ensure_ascii=False, separators=(",", ":"))
            os.replace(tmp, self.ruta)
        except OSError:
            log.exception("no pude guardar el historial del portapapeles")

    # ── lógica pura (testeable sin AppKit) ──────────────────────────────
    def agregar(self, texto, app=None, ts=None):
        texto = str(texto or "")
        if not texto.strip() or len(texto) > MAX_CARACTERES:
            return False
        with self._lock:
            self._entradas = [e for e in self._entradas if e["texto"] != texto]
            self._entradas.insert(0, {"texto": texto,
                                      "ts": time.time() if ts is None else float(ts),
                                      "app": str(app or "")})
            del self._entradas[self.max:]
            self._guardar()
        return True

    def olvidar(self, texto):
        """Quita un recorte concreto (⌘⌫ en el buscador)."""
        with self._lock:
            antes = len(self._entradas)
            self._entradas = [e for e in self._entradas if e["texto"] != texto]
            if len(self._entradas) == antes:
                return False
            self._guardar()
            return True

    def buscar(self, consulta="", limite=None):
        """Entradas que contienen TODAS las palabras de la consulta, sin
        importar tildes ni mayúsculas. Orden: lo último copiado primero."""
        palabras = normalizar(consulta).split()
        with self._lock:
            entradas = [dict(e) for e in self._entradas]
        if palabras:
            entradas = [e for e in entradas
                        if all(p in normalizar(e["texto"]) for p in palabras)]
        return entradas[:limite] if limite else entradas

    def vaciar(self):
        with self._lock:
            self._entradas = []
            self._guardar()

    # ── vigilancia del portapapeles ─────────────────────────────────────
    def vigilar(self):
        """Llamar cada ~1 s. Devuelve True si capturó algo nuevo.
        changeCount() es gratis; el contenido solo se lee cuando cambia."""
        if self._pb is None:
            return False
        try:
            c = self._pb.changeCount()
            if c == self._ultimo_cambio:
                return False
            # Si el cambio lo provocó restaurar() nosotros, lo absorbe sin
            # recapturar: el texto NO debe dar un salto al principio del menú.
            if c == self._cambio_restaurado:
                self._ultimo_cambio = c
                self._cambio_restaurado = None
                return False
            self._ultimo_cambio = c
            tipos = [str(t) for t in (self._pb.types() or [])]
            if any(p in tipos for p in _PRIVADOS):
                return False
            texto = self._pb.stringForType_(NSPasteboardTypeString)
            return self.agregar(texto, app=_app_frontal()) if texto else False
        except Exception:
            log.exception("fallo vigilando el portapapeles")
            return False

    def copiar(self, texto):
        """Texto nuevo al portapapeles (el del lector): este SÍ entra en el
        historial, porque no lo había copiado nadie antes."""
        texto = str(texto or "")
        if self._pb is None or not texto:
            return False
        try:
            with self._lock:
                self._pb.clearContents()
                return bool(self._pb.setString_forType_(texto, NSPasteboardTypeString))
        except Exception:
            log.exception("fallo copiando texto al portapapeles")
            return False

    def restaurar(self, texto):
        """Deja el texto en el portapapeles, listo para ⌘V."""
        texto = str(texto or "")
        if self._pb is None or not texto:
            return False
        try:
            with self._lock:
                self._pb.clearContents()
                ok = bool(self._pb.setString_forType_(texto, NSPasteboardTypeString))
                if ok:
                    self._cambio_restaurado = self._pb.changeCount()
            log.info("pergamino restaurar: ok=%s changeCount=%s", ok, self._pb.changeCount())
            return ok
        except Exception as e:
            log.exception("fallo restaurando texto al portapapeles: %s", e)
            return False


def _app_frontal():
    """Nombre de la app donde se copió («Brave Browser»), para dar contexto."""
    if NSWorkspace is None:
        return ""
    try:
        app = NSWorkspace.sharedWorkspace().frontmostApplication()
        return str(app.localizedName() or "") if app else ""
    except Exception:
        return ""
